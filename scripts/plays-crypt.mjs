// Encrypts the private plays (plays.private.html) into plays.enc.js, which plays.html unlocks
// in the browser with the team password. plays.private.html is gitignored and never published.
//
//   PLAYS_PASSWORD='...' node scripts/plays-crypt.mjs encrypt
//   PLAYS_PASSWORD='...' node scripts/plays-crypt.mjs decrypt   (rebuilds plays.private.html)
//
// plays.private.html is an HTML fragment: the play sections, then one <script> that creates the
// PlayAnimators. The browser inserts the HTML and then runs the script.
import { pbkdf2Sync, randomBytes, createCipheriv, createDecipheriv } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'plays.private.html');
const OUTPUT = join(ROOT, 'plays.enc.js');
const ITERATIONS = 600000;

const password = process.env.PLAYS_PASSWORD;
if (!password) {
  console.error('Set PLAYS_PASSWORD to the team password.');
  process.exit(1);
}

function deriveKey(salt, iterations = ITERATIONS) {
  return pbkdf2Sync(password, salt, iterations, 32, 'sha256');
}

function readEncrypted() {
  const text = readFileSync(OUTPUT, 'utf8');
  return JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
}

function existingSalt() {
  if (!existsSync(OUTPUT)) return null;
  const encrypted = readEncrypted();
  return encrypted.iterations === ITERATIONS ? Buffer.from(encrypted.salt, 'base64') : null;
}

function encrypt() {
  const source = readFileSync(SOURCE, 'utf8');
  const match = source.match(/^([\s\S]*?)<script>([\s\S]*)<\/script>\s*$/);
  if (!match) throw new Error('plays.private.html must end with a single <script> block.');
  const payload = JSON.stringify({ html: match[1].trim(), script: match[2] });

  // Keep the existing salt so the key browsers remembered still unlocks the new copy. The IV
  // must be fresh on every encryption.
  const salt = existingSalt() || randomBytes(16);
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', deriveKey(salt), iv);
  // Web Crypto's AES-GCM expects the auth tag appended to the ciphertext.
  const data = Buffer.concat([cipher.update(payload, 'utf8'), cipher.final(), cipher.getAuthTag()]);

  const encrypted = {
    iterations: ITERATIONS,
    salt: salt.toString('base64'),
    iv: iv.toString('base64'),
    data: data.toString('base64'),
  };
  writeFileSync(OUTPUT, `// Generated by scripts/plays-crypt.mjs. Do not edit.\nwindow.PLAYS_ENCRYPTED = ${JSON.stringify(encrypted)};\n`);
  console.log(`Wrote ${OUTPUT}`);
}

function decrypt() {
  const encrypted = readEncrypted();
  const data = Buffer.from(encrypted.data, 'base64');
  const decipher = createDecipheriv('aes-256-gcm', deriveKey(Buffer.from(encrypted.salt, 'base64'), encrypted.iterations), Buffer.from(encrypted.iv, 'base64'));
  decipher.setAuthTag(data.subarray(data.length - 16));
  const payload = JSON.parse(Buffer.concat([decipher.update(data.subarray(0, data.length - 16)), decipher.final()]).toString('utf8'));
  writeFileSync(SOURCE, `${payload.html}\n\n<script>${payload.script}</script>\n`);
  console.log(`Wrote ${SOURCE}`);
}

const mode = process.argv[2];
if (mode === 'encrypt') encrypt();
else if (mode === 'decrypt') decrypt();
else {
  console.error('Usage: node scripts/plays-crypt.mjs encrypt|decrypt');
  process.exit(1);
}
