// Encrypts the private pages (plays.private.html, stats.private.html) into plays.enc.js and
// stats.enc.js, which plays.html and stats.html unlock in the browser with the team password. The
// private files are gitignored and never published.
//
//   PLAYS_PASSWORD='...' node scripts/plays-crypt.mjs encrypt
//   PLAYS_PASSWORD='...' node scripts/plays-crypt.mjs decrypt   (rebuilds the private files)
//
// Each private file is an HTML fragment followed by one <script> (e.g. the play sections, then the
// script that creates the PlayAnimators). The browser inserts the HTML and then runs the script.
// Every page shares one salt, so the key a browser remembers unlocks all of them.
import { pbkdf2Sync, randomBytes, createCipheriv, createDecipheriv } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGES = [
  { source: 'plays.private.html', output: 'plays.enc.js', global: 'PLAYS_ENCRYPTED' },
  { source: 'stats.private.html', output: 'stats.enc.js', global: 'STATS_ENCRYPTED' },
].map((page) => ({ ...page, source: join(ROOT, page.source), output: join(ROOT, page.output) }));
// The plays were encrypted first; their salt is the one browsers have remembered keys for.
const SALT_PAGE = PAGES[0];
const ITERATIONS = 600000;

const password = process.env.PLAYS_PASSWORD;
if (!password) {
  console.error('Set PLAYS_PASSWORD to the team password.');
  process.exit(1);
}

function deriveKey(salt, iterations = ITERATIONS) {
  return pbkdf2Sync(password, salt, iterations, 32, 'sha256');
}

function readEncrypted(output) {
  const text = readFileSync(output, 'utf8');
  return JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
}

function existingSalt() {
  if (!existsSync(SALT_PAGE.output)) return null;
  const encrypted = readEncrypted(SALT_PAGE.output);
  return encrypted.iterations === ITERATIONS ? Buffer.from(encrypted.salt, 'base64') : null;
}

function encrypt({ source, output, global }, salt) {
  const text = readFileSync(source, 'utf8');
  const match = text.match(/^([\s\S]*?)<script>([\s\S]*)<\/script>\s*$/);
  if (!match) throw new Error(`${source} must end with a single <script> block.`);
  const payload = JSON.stringify({ html: match[1].trim(), script: match[2] });

  // The IV must be fresh on every encryption.
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', deriveKey(salt), iv);
  // Web Crypto's AES-GCM expects the auth tag appended to the ciphertext.
  const data = Buffer.concat([cipher.update(payload, 'utf8'), cipher.final(), cipher.getAuthTag()]);

  const encrypted = {
    iterations: ITERATIONS,
    salt: salt.toString('base64'),
    iv: iv.toString('base64'),
    data: data.toString('base64'),
  };
  writeFileSync(output, `// Generated by scripts/plays-crypt.mjs. Do not edit.\nwindow.${global} = ${JSON.stringify(encrypted)};\n`);
  console.log(`Wrote ${output}`);
}

function decrypt({ source, output }) {
  const encrypted = readEncrypted(output);
  const data = Buffer.from(encrypted.data, 'base64');
  const decipher = createDecipheriv('aes-256-gcm', deriveKey(Buffer.from(encrypted.salt, 'base64'), encrypted.iterations), Buffer.from(encrypted.iv, 'base64'));
  decipher.setAuthTag(data.subarray(data.length - 16));
  const payload = JSON.parse(Buffer.concat([decipher.update(data.subarray(0, data.length - 16)), decipher.final()]).toString('utf8'));
  writeFileSync(source, `${payload.html ? `${payload.html}\n\n` : ''}<script>${payload.script}</script>\n`);
  console.log(`Wrote ${source}`);
}

const mode = process.argv[2];
if (mode === 'encrypt') {
  // Keep the existing salt so the key browsers remembered still unlocks the new copies.
  const salt = existingSalt() || randomBytes(16);
  for (const page of PAGES) if (existsSync(page.source)) encrypt(page, salt);
} else if (mode === 'decrypt') {
  for (const page of PAGES) if (existsSync(page.output)) decrypt(page);
} else {
  console.error('Usage: node scripts/plays-crypt.mjs encrypt|decrypt');
  process.exit(1);
}
